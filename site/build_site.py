"""Build the web version (the page you can host on GitHub Pages) into site/dist/.

The ORIGINAL app (src/spiceyelectrons/web/) is never changed by this: we copy its files and add a
small shim that answers the page's /api/... calls inside the browser instead of from the Python helper.
Part tables come straight from parts.py, so there is only one copy of them.
"""
import json
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "src"))
from spiceyelectrons import __version__, __build_date__, __app_name__      # noqa: E402
from spiceyelectrons import parts as P                                      # noqa: E402

SHIM = os.path.join(HERE, "shim")
DATA_JS = os.path.join(SHIM, "data.generated.js")


def write_data(path=DATA_JS):
    data = {"app": __app_name__, "version": __version__, "build": __build_date__,
            "catalogue": {k: [v[0], v[1]] for k, v in P.CATALOGUE.items()},
            "diode": P.DIODE_MODELS, "bjt": P.BJT_MODELS, "mos": P.MOS_MODELS,
            "ledVf": P.LED_VF, "limits": P.LIMITS}
    with open(path, "w", encoding="utf-8") as f:
        f.write("// GENERATED by site/build_site.py from src/spiceyelectrons/parts.py - do not edit.\n")
        f.write("export const DATA = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")
    return path


WEB = os.path.join(ROOT, "src", "spiceyelectrons", "web")
DIST = os.path.join(HERE, "dist")
SHIM_FILES = ["engine-shim.js", "worker.js", "netlist.js", "results.js", "pyfmt.js", "units.js", "data.generated.js", "site.css"]


def find_engine(engine_dir=None):
    """Folder holding eecircuit-engine.mjs (+ its licence). Installed by `npm install eecircuit-engine` at deploy time."""
    for d in [engine_dir, os.environ.get("EEC_DIR"), os.path.join(HERE, "node_modules", "eecircuit-engine"),
              "/tmp/eec/node_modules/eecircuit-engine"]:
        if d and os.path.exists(os.path.join(d, "dist", "eecircuit-engine.mjs")):
            return d
    raise SystemExit("eecircuit-engine not found. Run: cd site && npm install eecircuit-engine@1.9.0")


def build(dist=DIST, engine_dir=None):
    """Copy the ORIGINAL web files (read only) into dist, add the shim + yellow bar + engine. src/ is never written."""
    eng = find_engine(engine_dir)
    write_data()
    if os.path.isdir(dist):
        shutil.rmtree(dist)
    shutil.copytree(WEB, dist)
    sh = os.path.join(dist, "shim")
    os.makedirs(os.path.join(sh, "engine"))
    for f in SHIM_FILES:
        shutil.copy(os.path.join(SHIM, f), sh)
    shutil.copy(os.path.join(eng, "dist", "eecircuit-engine.mjs"), os.path.join(sh, "engine"))
    lic = os.path.join(eng, "LICENSE")
    with open(os.path.join(sh, "engine", "LICENSE-eecircuit-engine.txt"), "w", encoding="utf-8") as o:
        o.write(open(lic, encoding="utf-8").read() if os.path.exists(lic) else
                "eecircuit-engine (MIT licence), https://github.com/eelab-dev/EEcircuit-engine - ngspice compiled to WebAssembly.\n")
    idx = os.path.join(dist, "index.html")
    h = open(idx, encoding="utf-8").read()
    if "app.js" not in h:
        raise SystemExit("index.html no longer loads app.js - update site/build_site.py")
    h = h.replace("</head>", '<link rel="stylesheet" href="shim/site.css">\n</head>', 1)
    h = re.sub(r'<script src="app.js"></script>', '<script src="shim/engine-shim.js"></script>\n<script src="app.js"></script>', h, count=1)
    if "engine-shim.js" not in h:
        raise SystemExit("could not inject the shim before app.js - update site/build_site.py")
    open(idx, "w", encoding="utf-8").write(h)
    open(os.path.join(dist, ".nojekyll"), "w").close()
    return dist


if __name__ == "__main__":
    if "--data-only" in sys.argv:
        print("wrote", write_data())
    else:
        print("built", build(engine_dir=sys.argv[1] if len(sys.argv) > 1 else None))
